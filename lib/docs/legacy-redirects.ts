export interface ILegacyDocsRedirect {
  /** The locale prefix the old address had, if any. */
  locale?: string
  /** The new path, without a locale prefix. */
  target: string
}

/** Where an old address such as /zh-CN/guides/pro/license lives now; undefined when it is not an old address. */
export function resolveLegacyDocsPath(pathname: string, locales: readonly string[]): ILegacyDocsRedirect | undefined {
  const match = pathname.match(new RegExp(`^(?:/(${locales.join('|')}))?(/.*?)/?$`))
  const target = match && LEGACY_DOCS_PATHS.get(match[2])
  return target ? { locale: match[1], target } : undefined
}
