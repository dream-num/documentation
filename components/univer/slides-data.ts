const SLIDE_WIDTH = 840
const SLIDE_HEIGHT = 472.5
const CARD_PADDING = { left: 18, top: 14, right: 18, bottom: 14 }

interface ITextShapeOptions {
  bold?: boolean
  color: string
  fontSize: number
  height: number
  id: string
  left: number
  text: string
  top: number
  width: number
}

interface ICardShapeOptions extends ITextShapeOptions {
  fill: string
  shapeType?: ShapeTypeEnum
  stroke: string
}

function createTextShape(options: ITextShapeOptions): ISlideShapeElement {
  return {
    id: options.id,
    type: PageElementTypeEnum.Shape,
    transform: {
      left: options.left,
      top: options.top,
      width: options.width,
      height: options.height,
      rotation: 0,
    },
    shapeData: {
      shapeType: ShapeTypeEnum.Rect,
      isTextBox: true,
      fill: { fillType: ShapeFillEnum.NoFill },
      stroke: { lineStrokeType: ShapeLineTypeEnum.NoLine },
      textRectPadding: { left: 0, top: 0, right: 0, bottom: 0 },
      shapeText: {
        isHorizontal: true,
        isRichText: false,
        text: options.text,
        color: options.color,
        fontFamily: 'Arial',
        fontSize: options.fontSize,
        bold: options.bold,
        autoFitType: ShapeTextAutoFitType.NormAutoFit,
        textWrap: ShapeTextWrapType.Square,
      },
    },
  }
}

function createCenteredTextShape(options: ITextShapeOptions): ISlideShapeElement {
  return {
    id: options.id,
    type: PageElementTypeEnum.Shape,
    transform: {
      left: options.left,
      top: options.top,
      width: options.width,
      height: options.height,
      rotation: 0,
    },
    shapeData: {
      shapeType: ShapeTypeEnum.Rect,
      fill: { fillType: ShapeFillEnum.NoFill },
      stroke: { lineStrokeType: ShapeLineTypeEnum.NoLine },
      textRectPadding: { left: 0, top: 0, right: 0, bottom: 0 },
      shapeText: {
        isHorizontal: true,
        isRichText: false,
        text: options.text,
        color: options.color,
        fontFamily: 'Arial',
        fontSize: options.fontSize,
        bold: options.bold,
        autoFitType: ShapeTextAutoFitType.NoAutoFit,
        textWrap: ShapeTextWrapType.Square,
      },
    },
  }
}

function createCardShape(options: ICardShapeOptions): ISlideShapeElement {
  return {
    id: options.id,
    type: PageElementTypeEnum.Shape,
    transform: {
      left: options.left,
      top: options.top,
      width: options.width,
      height: options.height,
      rotation: 0,
    },
    shapeData: {
      shapeType: options.shapeType ?? ShapeTypeEnum.RoundRect,
      fill: { fillType: ShapeFillEnum.SolidFill, color: options.fill },
      stroke: { lineStrokeType: ShapeLineTypeEnum.SolidLine, color: options.stroke, width: 1 },
      textRectPadding: CARD_PADDING,
      shapeText: {
        isHorizontal: true,
        isRichText: false,
        text: options.text,
        color: options.color,
        fontFamily: 'Arial',
        fontSize: options.fontSize,
        bold: options.bold,
        autoFitType: ShapeTextAutoFitType.NormAutoFit,
        textWrap: ShapeTextWrapType.Square,
      },
    },
  }
}

function createDecorativeShape(
  id: string,
  shapeType: ShapeTypeEnum,
  left: number,
  top: number,
  width: number,
  height: number,
  fill: string,
  stroke = fill,
): ISlideShapeElement {
  return {
    id,
    type: PageElementTypeEnum.Shape,
    transform: { left, top, width, height, rotation: 0 },
    shapeData: {
      shapeType,
      fill: { fillType: ShapeFillEnum.SolidFill, color: fill },
      stroke: { lineStrokeType: ShapeLineTypeEnum.SolidLine, color: stroke, width: 0 },
    },
  }
}

function createContentSlide(
  id: string,
  chapter: string,
  title: string,
  subtitle: string,
  instruction: string,
): ISlidePage {
  const elements = [
    createTextShape({
      id: 'chapter',
      left: 54,
      top: 26,
      width: 700,
      height: 18,
      text: chapter,
      color: '#0F766E',
      fontSize: 10,
      bold: true,
    }),
    createTextShape({
      id: 'title',
      left: 54,
      top: 52,
      width: 732,
      height: 44,
      text: title,
      color: '#102A43',
      fontSize: 29,
      bold: true,
    }),
    createTextShape({
      id: 'subtitle',
      left: 56,
      top: 100,
      width: 730,
      height: 28,
      text: subtitle,
      color: '#627D98',
      fontSize: 13,
    }),
    createTextShape({
      id: 'instruction',
      left: 54,
      top: 435,
      width: 734,
      height: 22,
      text: instruction,
      color: '#0F766E',
      fontSize: 11,
      bold: true,
    }),
  ]
  return {
    id,
    pageType: PageTypeEnum.Slide,
    name: title,
    background: { type: SlideBackgroundTypeEnum.Solid, color: '#FFFFFF' },
    elementOrder: elements.map((element) => element.id),
    elements: Object.fromEntries(elements.map((element) => [element.id, element])),
  }
}

